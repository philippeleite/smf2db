package main

import "testing"

func TestSmf006Acct(t *testing.T) {
	// Example from the manual: JOB accounting (TSS40000,JROMXB,1234,5,4321,,3,N,254)
	acct := []byte{0x09,
		0x08, 0xe3, 0xe2, 0xe2, 0xf4, 0xf0, 0xf0, 0xf0, 0xf0,
		0x06, 0xd1, 0xd9, 0xd6, 0xd4, 0xe7, 0xc2,
		0x04, 0xf1, 0xf2, 0xf3, 0xf4,
		0x01, 0xf5,
		0x04, 0xf4, 0xf3, 0xf2, 0xf1,
		0x00,
		0x01, 0xf3,
		0x01, 0xd5,
		0x03, 0xf2, 0xf5, 0xf4,
	}
	want := " TSS40000 JROMXB 1234 5 4321  3 N 254 "
	if got := smf006Acct(acct); got != want {
		t.Errorf("smf006Acct: got %q, want %q", got, want)
	}
}

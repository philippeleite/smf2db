// Type 80 (RACF processing). The layout comes from z/OS Security Server RACF Macros and Interfaces
// (SA23-2288, data/icha300_v3r1.pdf), not from the SMF manual. smf080 holds the fixed header; the relocate
// sections (1-byte type and length) go to smf080_reloc and the extended-length relocate sections (2-byte
// type and length) to smf080_reloc2, with ID and SEQ. Both kinds are located by offsets from SMF80FLG,
// which is rec[0]. Section data is stored as text when the manual lists the data type as EBCDIC, and as
// hex digits otherwise (binary and mixed types such as 6, command-related data, which is not decoded).
//
// Three reference tables, built from the manual, give readable names for joins: smf080_events (SMF80EVT),
// smf080_qualifiers (SMF80EVT, SMF80EVQ) and smf080_types (relocate data types, with their format).

var pStmt080, pStmt080Reloc, pStmt080Reloc2 *sql.Stmt
var once080 sync.Once
var count080 int

var smf080Fields = fields{
	{"SMF80TME", 2, 'T', 4},
	{"SMF80DTE", 6, 'd', 4},
	{"SMF80SID", 10, 'c', 4},
	{"SMF80DES", 14, 'u', 2},
	{"SMF80EVT", 16, 'u', 1},
	{"SMF80EVQ", 17, 'u', 1},
	{"SMF80USR", 18, 'c', 8},
	{"SMF80GRP", 26, 'c', 8},
	{"SMF80REL", 34, 'u', 2},
	{"SMF80CNT", 36, 'u', 2},
	{"SMF80ATH", 38, 'u', 1},
	{"SMF80REA", 39, 'u', 1},
	{"SMF80TLV", 40, 'u', 1},
	{"SMF80ERR", 41, 'u', 1},
	{"SMF80TRM", 42, 'c', 8},
	{"SMF80JBN", 50, 'c', 8},
	{"SMF80RST", 58, 'T', 4},
	{"SMF80RSD", 62, 'd', 4},
	{"SMF80UID", 66, 'c', 8},
	{"SMF80VER", 74, 'u', 1},
	{"SMF80RE2", 75, 'u', 1},
	{"SMF80VRM", 76, 'c', 4},
	{"SMF80SEC", 80, 'c', 8},
	{"SMF80RL2", 88, 'u', 2},
	{"SMF80CT2", 90, 'u', 2},
	{"SMF80AU2", 92, 'u', 1},
}

func smf080Init() {
	cols := smf080Fields.columns()
	pStmt080 = createTable("smf080", "ID INT NOT NULL, "+cols)
	pStmt080Reloc = createTable("smf080_reloc", "ID INT NOT NULL, SEQ INT NOT NULL, SMF80DTP INT, SMF80DLN INT, SMF80DTA TEXT")
	pStmt080Reloc2 = createTable("smf080_reloc2", "ID INT NOT NULL, SEQ INT NOT NULL, SMF80TP2 INT, SMF80DL2 INT, SMF80DA2 TEXT")

	ev := createTable("smf080_events", "SMF80EVT INT NOT NULL, EVENT TEXT")
	for k, v := range smf080Events {
		insert(ev, k, v)
	}
	qu := createTable("smf080_qualifiers", "SMF80EVT INT NOT NULL, SMF80EVQ INT NOT NULL, DESCRIPTION TEXT")
	for k, v := range smf080Qualifiers {
		insert(qu, k/256, k%256, v)
	}
	ty := createTable("smf080_types", "TYPE INT NOT NULL, FORMAT TEXT, DESCRIPTION TEXT")
	for k, v := range smf080Types {
		insert(ty, k, v.format, v.desc)
	}
}

func smf080Parse(rec []byte) {
	once080.Do(smf080Init)

	s := section(rec)
	count080 += 1
	insert(pStmt080, append([]interface{}{count080}, smf080Fields.values(s)...)...)

	// relocate sections: 1-byte type and length
	off := s.num(34, 2)
	for k := 0; k < s.num(36, 2); k++ {
		t, n := s.num(off, 1), s.num(off+1, 1)
		insert(pStmt080Reloc, count080, k+1, t, n, smf080Data(t, s.sub(off+2, n)))
		off += 2 + n
	}
	// extended-length relocate sections: 2-byte type and length
	off = s.num(88, 2)
	for k := 0; k < s.num(90, 2); k++ {
		t, n := s.num(off, 2), s.num(off+2, 2)
		insert(pStmt080Reloc2, count080, k+1, t, n, smf080Data(t, s.sub(off+4, n)))
		off += 4 + n
	}
}

// smf080Data returns relocate section data as text for EBCDIC data types, as hex digits otherwise.
func smf080Data(t int, b section) interface{} {
	if b == nil {
		return nil
	}
	if smf080Types[t].format == "ebcdic" {
		return ebcdic(b)
	}
	return fmt.Sprintf("%X", []byte(b))
}


// Type 71 (RMF paging activity): smf071 holds the header and RMF product section, smf071_paging the paging
// data section. The swap placement section has held no valid values since z/OS V1R13 and is not decoded.
// The field table was generated from the manual with tools/genfields.py.

var pStmt071, pStmt071Paging *sql.Stmt
var once071 sync.Once
var count071 int

func smf071Init() {
	pStmt071 = createTable("smf071", rmfColumns("SMF71"))
	pStmt071Paging = createTable("smf071_paging", "ID INT NOT NULL, "+smf071PagingFields.columns())
}

func smf071Parse(rec []byte) {
	once071.Do(smf071Init)

	count071 += 1
	insert(pStmt071, rmfRow(rec, count071, "SMF71")...)
	off, length, n := tripletAt(rec, 32) // paging data section
	for k := 0; k < n; k++ {
		insert(pStmt071Paging, append([]interface{}{count071},
			smf071PagingFields.values(section(rec).sub(off+k*length, length))...)...)
	}
}

